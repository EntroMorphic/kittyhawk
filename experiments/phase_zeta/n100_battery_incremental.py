def mode_env(mode: str, window: int) -> dict:
    if mode == "no_evict":
        return {"BITNET_KV_EVICT_MODE": "none"}
    if mode == "fifo":
        return {"BITNET_KV_EVICT_MODE": "fifo", "BITNET_KV_WINDOW": str(window)}
    if mode == "sigdist":
        return {"BITNET_KV_EVICT_MODE": "sigdist", "BITNET_KV_WINDOW": str(window),
                "BITNET_ATTN_FIXED_TAU": "5000"}
    if mode == "qsigdist":
        return {"BITNET_KV_EVICT_MODE": "qsigdist", "BITNET_KV_WINDOW": str(window),
                "BITNET_ATTN_FIXED_TAU": "5000"}
    if mode == "random":
        return {"BITNET_KV_EVICT_MODE": "random", "BITNET_KV_WINDOW": str(window),
                "BITNET_KV_EVICT_SEED": "42"}
    raise ValueError(mode)


def run_one(label: str, prompt: str, mode: str, window: int) -> dict:
    env = os.environ.copy()
    env.update(mode_env(mode, window))
    cmd = [HARNESS, DATA, "--prompt-tokens", prompt, "--gen", str(GEN_N)]
    t0 = time.time()
    proc = subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=1800)
    elapsed = time.time() - t0
    out = proc.stdout + proc.stderr
    os.makedirs(OUTDIR, exist_ok=True)
    with open(os.path.join(OUTDIR, f"{label}_{mode}.log"), "w") as f:
        f.write(out)
    m = re.search(r"generated tokens\s*=\s*([\d\s\-]+)", out)
    tokens = [int(t) for t in m.group(1).strip().split()] if m else None
    return {"label": label, "mode": mode, "tokens": tokens,
            "elapsed_s": elapsed, "exit": proc.returncode}


def match_rate(base, cand):
    n = min(len(base), len(cand))
    return sum(1 for i in range(n) if base[i] == cand[i]) / n if n else float('nan')


def divergence(a, b):
    for i in range(min(len(a), len(b))):
        if a[i] != b[i]: return i
    return min(len(a), len(b))


def run_battery():
    os.makedirs(OUTDIR, exist_ok=True)
    modes = ["no_evict", "fifo", "random", "sigdist", "qsigdist"]
    all_results = []
    print(f"N={len(NEW_PROMPTS)} NEW prompts × {len(modes)} modes × "
          f"window={WINDOW} × gen={GEN_N}")
    print(f"{'label':<22} {'mode':<10} {'elapsed':>9}  tokens[:14]")
    print("-" * 110)
    out_path = os.path.join(OUTDIR, "battery_results.json")
    for i, (label, prompt) in enumerate(NEW_PROMPTS.items()):
        for mode in modes:
            r = run_one(label, prompt, mode, WINDOW)
            all_results.append(r)
            toks = r["tokens"] or []
            tok_str = " ".join(str(t) for t in toks[:14])
            print(f"[{i+1:>2d}/{len(NEW_PROMPTS)}] {label:<14} {mode:<10} "
                  f"{r['elapsed_s']:>7.2f}s  {tok_str}", flush=True)
        # Save incrementally so a crash doesn't lose work
        with open(out_path, "w") as f:
            json.dump({"config": {"window": WINDOW, "gen_n": GEN_N,
                                  "n_prompts": len(NEW_PROMPTS),
                                  "label_set": "n100_new_50"},
                       "trials": all_results}, f, indent=2)
    print(f"\nResults: {out_path}")


def merge_and_analyze():
    """Pool the new 50 with the existing 50 and report combined CIs."""
    new_path = os.path.join(OUTDIR, "battery_results.json")
    if not os.path.exists(new_path):
        print(f"ERROR: {new_path} not found. Run without --merge first.")
        sys.exit(1)
    if not os.path.exists(N50_JSON):
        print(f"ERROR: existing N=50 results not found at {N50_JSON}.")
        sys.exit(1)
    with open(new_path) as f:
        new = json.load(f)
    with open(N50_JSON) as f:
        old = json.load(f)
    pooled = old["trials"] + new["trials"]
    # Verify no label collision (which would corrupt the pool)
    old_labels = {t["label"] for t in old["trials"]}
    new_labels = {t["label"] for t in new["trials"]}
    overlap = old_labels & new_labels
    if overlap:
        print(f"ERROR: label overlap between N=50 and N=50_new: {sorted(overlap)}")
        sys.exit(1)
    all_labels = sorted(old_labels | new_labels)
    print(f"Pooled N={len(all_labels)} prompts ({len(old_labels)} old + "
          f"{len(new_labels)} new)\n")

    by_lm = {(r["label"], r["mode"]): r for r in pooled}
    rng = np.random.default_rng(RNG_SEED)
    print(f"=== window={WINDOW} aggregate (POOLED N=100) ===\n")
    for mode in ("fifo", "random", "sigdist", "qsigdist"):
        per_prompt_match = []
        per_prompt_div = []
        for label in all_labels:
            base = by_lm.get((label, "no_evict"), {}).get("tokens")
            cand = by_lm.get((label, mode), {}).get("tokens")
            if not base or not cand: continue
            per_prompt_match.append(match_rate(base, cand))
            per_prompt_div.append(divergence(base, cand))
        arr = np.array(per_prompt_match)
        boots = []
        for _ in range(5000):
            idx = rng.integers(0, len(arr), size=len(arr))
            boots.append(arr[idx].mean())
        ci_lo, ci_hi = np.quantile(boots, [0.025, 0.975])
        print(f"  {mode:<9} mean_div={np.mean(per_prompt_div):>5.1f}  "
              f"match={arr.mean()*100:>5.1f}%  "
              f"95%CI=[{ci_lo*100:>5.1f}, {ci_hi*100:>5.1f}]%  "
              f"std={arr.std()*100:>5.1f}pp  N={len(arr)}")

    # Paired comparison vs random — main inferential statistic
    print(f"\n=== Paired Δ vs random (95% CI from prompt-resampled bootstrap, POOLED N=100) ===\n")
    rng = np.random.default_rng(RNG_SEED)
    for mode in ("fifo", "sigdist", "qsigdist"):
        diffs = []
        for label in all_labels:
            base = by_lm.get((label, "no_evict"), {}).get("tokens")
            cand = by_lm.get((label, mode), {}).get("tokens")
            randc = by_lm.get((label, "random"), {}).get("tokens")
            if not (base and cand and randc): continue
            diffs.append(match_rate(base, cand) - match_rate(base, randc))
        d = np.array(diffs)
        boots = []
        for _ in range(5000):
            idx = rng.integers(0, len(d), size=len(d))
            boots.append(d[idx].mean())
        ci_lo, ci_hi = np.quantile(boots, [0.025, 0.975])
        wins = int(np.sum(d > 0))
        losses = int(np.sum(d < 0))
        ties = int(np.sum(d == 0))
        sig = "**SIGNIFICANT**" if (ci_lo > 0 or ci_hi < 0) else "(not significant)"
        print(f"  {mode:<9} Δ={d.mean()*100:+5.1f}pp  "
              f"95%CI=[{ci_lo*100:+5.1f}, {ci_hi*100:+5.1f}]pp  "
              f"wins/ties/losses = {wins}/{ties}/{losses} of {len(d)}   {sig}")

    # Also report split-half: do the 50-old and 50-new agree directionally?
    print(f"\n=== Split-half consistency (N=50 old vs N=50 new) ===\n")
    for mode in ("sigdist", "qsigdist"):
        d_old, d_new = [], []
        for label in old_labels:
            b = by_lm.get((label, "no_evict"), {}).get("tokens")
            c = by_lm.get((label, mode), {}).get("tokens")
            r = by_lm.get((label, "random"), {}).get("tokens")
            if b and c and r:
                d_old.append(match_rate(b, c) - match_rate(b, r))
        for label in new_labels:
            b = by_lm.get((label, "no_evict"), {}).get("tokens")
            c = by_lm.get((label, mode), {}).get("tokens")
            r = by_lm.get((label, "random"), {}).get("tokens")
            if b and c and r:
                d_new.append(match_rate(b, c) - match_rate(b, r))
        d_old = np.array(d_old); d_new = np.array(d_new)
        agree = (d_old.mean() > 0) == (d_new.mean() > 0)
        print(f"  {mode:<9} old Δ={d_old.mean()*100:+5.1f}pp (N={len(d_old)})   "
              f"new Δ={d_new.mean()*100:+5.1f}pp (N={len(d_new)})   "
              f"agree_direction={'YES' if agree else 'NO'}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--merge", action="store_true",
                    help="Skip the run; just merge existing new + N=50 results")
    args = ap.parse_args()
    if args.merge:
        merge_and_analyze()
    else:
        run_battery()


if __name__ == "__main__":
    main()
